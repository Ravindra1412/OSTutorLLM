"""
app/ai/providers/mock_provider.py

The local-development/offline provider (Section 14 — "No Internet"
fallback strategy, made proactive rather than purely reactive). Used
automatically when AI_PROVIDER=mock (the default in .env.example) so
the entire Tutor Engine — workflow enforcement, memory, conversation
persistence, safety layer, formatting, logging — is runnable and
testable end-to-end without any API key or external network access.

This is NOT a fallback-on-error stand-in for a real provider's output
quality (it does not generate genuinely intelligent tutoring content);
it deterministically echoes back a structurally-correct response
matching whatever hint stage the Prompt Manager requested, based on
markers already present in the constructed prompt. This is sufficient
to prove the surrounding engineering (the actual deliverable of this
phase) is correct, while being honest that response *quality* depends
on wiring in a real provider (OpenAI/Ollama/DeepSeek), which this
phase's provider abstraction makes a one-line config change to do.
"""

import re

from app.ai.providers.base import LLMProvider, LLMMessage, LLMResponse


class MockProvider(LLMProvider):
    name = "mock"

    def generate(self, messages: list[LLMMessage], temperature: float, max_tokens: int, timeout: float) -> LLMResponse:
        developer_msg = next((m.content for m in messages if m.role == "system" and "HINT_STAGE=" in m.content), "")
        stage_match = re.search(r"HINT_STAGE=(\d+)", developer_msg)
        topic_match = re.search(r"TOPIC=([^\n]+)", developer_msg)
        stage = int(stage_match.group(1)) if stage_match else 0
        topic = topic_match.group(1).strip() if topic_match else "this topic"

        last_user = next((m.content for m in reversed(messages) if m.role == "user"), "")

        text = _mock_reply_for_stage(stage, topic, last_user)
        return LLMResponse(text=text, provider=self.name, model="mock-tutor-v1", raw={"stage": stage})


def _mock_reply_for_stage(stage: int, topic: str, student_message: str) -> str:
    if stage == 0:
        return (
            f"Before I answer, let's think it through — what do you already know about **{topic}**? "
            f"What have you tried so far for: \"{student_message.strip()[:120]}\"?"
        )
    if stage == 1:
        return (
            f"**Hint 1/3:** You're on the right track. Think about which specific command or concept in "
            f"**{topic}** applies here, and why it fits this situation."
        )
    if stage == 2:
        return (
            f"**Hint 2/3:** Let's narrow it down further. Consider the exact syntax or option flags involved "
            f"in **{topic}** — what structure does the solution need?"
        )
    if stage == 3:
        return (
            f"**Hint 3/3:** You're very close. Try assembling the full command or script now based on what "
            f"we've covered about **{topic}**, and tell me what you come up with."
        )
    return (
        f"**Full explanation:** Here's the complete solution for **{topic}**, step by step, along with why "
        f"it works this way. (In a live deployment, this section is generated by the configured LLM provider "
        f"with full topic-specific detail.)"
    )
